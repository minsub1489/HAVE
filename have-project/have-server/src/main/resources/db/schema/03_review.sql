-- HAVE 스키마 03 — 검토 (수정 회차 3개는 05에)
-- 기준: 팀원공유용_v3/11_DB/HAVE_데이터베이스_설계_검토반영.md의 최종 스키마(형식은 6단계, 코드 값은 부록 A).
-- 설계서의 스키마 정의(팀원공유용_v3/_소스/schema_1123.py)를 그대로 옮겼다. 이제부터는 이 파일이 원본이고 테이블 담당자가 고친다.
-- 설계서와 다르게 둔 곳(기본값 · NULL 허용 · 자동 번호)은 docs/design-changes.md에 적었다.
-- 여러 번 실행해도 되도록 IF NOT EXISTS를 쓴다. 열을 바꾸면 이 파일을 고치고, 이미 만든 로컬 DB는 지우고 다시 만든다.

-- GATE_POLICY · 위험 등급 기준 (담당 B)
CREATE TABLE IF NOT EXISTS gate_policy (
    policy_version   VARCHAR(20),
    medium_min_total SMALLINT NOT NULL,
    high_min_total   SMALLINT NOT NULL,
    CONSTRAINT pk_gate_policy PRIMARY KEY (policy_version)
);

-- RISK_ASSESSMENT · 위험 평가 (담당 B)
-- 등급(LOW·MEDIUM·HIGH)은 저장하지 않고 점수 합계로 계산한다.
CREATE TABLE IF NOT EXISTS risk_assessment (
    version_id         BIGINT,
    assessment_seq     INT,
    policy_version     VARCHAR(20) NOT NULL,
    ai_usage_score     SMALLINT NOT NULL,
    importance_score   SMALLINT NOT NULL,
    evidence_gap_score SMALLINT NOT NULL,
    past_failure_score SMALLINT NOT NULL,
    rationale          VARCHAR(2000) NOT NULL,
    CONSTRAINT pk_risk_assessment PRIMARY KEY (version_id, assessment_seq),
    CONSTRAINT fk_risk_assessment_version_id FOREIGN KEY (version_id) REFERENCES work_version (version_id),
    CONSTRAINT fk_risk_assessment_policy_version FOREIGN KEY (policy_version) REFERENCES gate_policy (policy_version),
    CONSTRAINT ck_risk_assessment_ai_usage_score CHECK (ai_usage_score BETWEEN 0 AND 3),
    CONSTRAINT ck_risk_assessment_importance_score CHECK (importance_score BETWEEN 0 AND 3),
    CONSTRAINT ck_risk_assessment_evidence_gap_score CHECK (evidence_gap_score BETWEEN 0 AND 2),
    CONSTRAINT ck_risk_assessment_past_failure_score CHECK (past_failure_score BETWEEN 0 AND 2)
);

-- REVIEW_REQUEST · 검토 요청 (담당 B)
CREATE TABLE IF NOT EXISTS review_request (
    request_id     BIGINT GENERATED BY DEFAULT AS IDENTITY,
    version_id     BIGINT NOT NULL,
    assessment_seq INT NOT NULL,
    reviewer_id    BIGINT NOT NULL,
    state          VARCHAR(30) NOT NULL,
    message        VARCHAR(1000),
    due_date       DATE,
    requested_at   TIMESTAMP NOT NULL,
    CONSTRAINT pk_review_request PRIMARY KEY (request_id),
    CONSTRAINT fk_review_request_risk_assessment FOREIGN KEY (version_id, assessment_seq) REFERENCES risk_assessment (version_id, assessment_seq),
    CONSTRAINT fk_review_request_reviewer_id FOREIGN KEY (reviewer_id) REFERENCES "user" (user_id),
    CONSTRAINT ck_review_request_state CHECK (state IN ('REQUESTED', 'IN_REVIEW', 'CLOSED', 'CANCELED'))
);
-- 버전당 진행 중인 검토 요청은 최대 1개
CREATE UNIQUE INDEX IF NOT EXISTS uq_review_request_active ON review_request (version_id) WHERE state IN ('REQUESTED', 'IN_REVIEW');

-- CHALLENGE · 이해 확인 과제 (담당 B)
CREATE TABLE IF NOT EXISTS challenge (
    challenge_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    request_id   BIGINT NOT NULL,
    kind         VARCHAR(30) NOT NULL,
    prompt       TEXT NOT NULL,
    rubric       TEXT NOT NULL,
    CONSTRAINT pk_challenge PRIMARY KEY (challenge_id),
    CONSTRAINT fk_challenge_request_id FOREIGN KEY (request_id) REFERENCES review_request (request_id),
    CONSTRAINT ck_challenge_kind CHECK (kind IN ('TEACH_BACK', 'FAULT_INJECTION', 'WHAT_IF'))
);

-- CHALLENGE_RESPONSE · 과제 답변 (담당 B)
CREATE TABLE IF NOT EXISTS challenge_response (
    response_id  BIGINT GENERATED BY DEFAULT AS IDENTITY,
    challenge_id BIGINT NOT NULL UNIQUE,
    answer       TEXT NOT NULL,
    confidence   VARCHAR(30),
    submitted_at TIMESTAMP,
    CONSTRAINT pk_challenge_response PRIMARY KEY (response_id),
    CONSTRAINT fk_challenge_response_challenge_id FOREIGN KEY (challenge_id) REFERENCES challenge (challenge_id),
    CONSTRAINT ck_challenge_response_confidence CHECK (confidence IN ('LOW', 'MEDIUM', 'HIGH'))
);

-- EVALUATION · 과제 평가 (담당 B)
CREATE TABLE IF NOT EXISTS evaluation (
    response_id BIGINT,
    score       SMALLINT NOT NULL,
    reason      VARCHAR(2000) NOT NULL,
    critical    BOOLEAN NOT NULL,
    CONSTRAINT pk_evaluation PRIMARY KEY (response_id),
    CONSTRAINT fk_evaluation_response_id FOREIGN KEY (response_id) REFERENCES challenge_response (response_id),
    CONSTRAINT ck_evaluation_score CHECK (score BETWEEN 0 AND 2)
);

-- REVIEW · 검토 회차 (담당 B)
-- review_digest는 검토를 끝낼 때 정해지므로 진행 중에는 비어 있다(설계서와 다른 점: NULL 허용).
CREATE TABLE IF NOT EXISTS review (
    review_id     BIGINT GENERATED BY DEFAULT AS IDENTITY,
    request_id    BIGINT NOT NULL UNIQUE,
    state         VARCHAR(30) NOT NULL,
    memo          VARCHAR(2000) DEFAULT '' NOT NULL,
    review_digest CHAR(64),
    CONSTRAINT pk_review PRIMARY KEY (review_id),
    CONSTRAINT fk_review_request_id FOREIGN KEY (request_id) REFERENCES review_request (request_id),
    CONSTRAINT ck_review_state CHECK (state IN ('IN_PROGRESS', 'COMPLETED', 'HALTED'))
);

-- CHECKLIST_ITEM · 체크리스트 항목 (담당 B)
CREATE TABLE IF NOT EXISTS checklist_item (
    item_id   BIGINT GENERATED BY DEFAULT AS IDENTITY,
    criterion VARCHAR(200) NOT NULL,
    required  BOOLEAN NOT NULL,
    CONSTRAINT pk_checklist_item PRIMARY KEY (item_id)
);

-- REVIEW_CHECK · 체크 결과 (담당 B)
CREATE TABLE IF NOT EXISTS review_check (
    review_id BIGINT,
    item_id   BIGINT,
    checked   BOOLEAN NOT NULL,
    CONSTRAINT pk_review_check PRIMARY KEY (review_id, item_id),
    CONSTRAINT fk_review_check_review_id FOREIGN KEY (review_id) REFERENCES review (review_id),
    CONSTRAINT fk_review_check_item_id FOREIGN KEY (item_id) REFERENCES checklist_item (item_id)
);

-- FEEDBACK · 검토 의견·판정 (담당 B)
CREATE TABLE IF NOT EXISTS feedback (
    review_id          BIGINT,
    evaluation_summary VARCHAR(2000) NOT NULL,
    comment            VARCHAR(2000) NOT NULL,
    decision           VARCHAR(30) NOT NULL,
    CONSTRAINT pk_feedback PRIMARY KEY (review_id),
    CONSTRAINT fk_feedback_review_id FOREIGN KEY (review_id) REFERENCES review (review_id),
    CONSTRAINT ck_feedback_decision CHECK (decision IN ('PASS', 'REVISION_REQUIRED'))
);

-- FEEDBACK_ITEM · 보완 요청 항목 (담당 B)
CREATE TABLE IF NOT EXISTS feedback_item (
    feedback_item_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    review_id        BIGINT NOT NULL,
    target_section   VARCHAR(100) NOT NULL,
    content          VARCHAR(1000) NOT NULL,
    CONSTRAINT pk_feedback_item PRIMARY KEY (feedback_item_id),
    CONSTRAINT fk_feedback_item_review_id FOREIGN KEY (review_id) REFERENCES feedback (review_id)
);
