-- 기준: 팀원공유용_v3/11_DB/HAVE_데이터베이스_설계_검토반영.md의 최종 스키마(형식은 6단계, 코드 값은 부록 A).
-- 설계서의 스키마 정의(팀원공유용_v3/_소스/schema_1123.py)를 그대로 옮겼다. 이제부터는 이 파일이 원본이고 테이블 담당자가 고친다.
-- 설계서와 다르게 둔 곳(기본값 · NULL 허용 · 자동 번호)은 docs/design-changes.md에 적었다.
-- 여러 번 실행해도 되도록 IF NOT EXISTS를 쓴다. 열을 바꾸면 이 파일을 고치고, 이미 만든 로컬 DB는 지우고 다시 만든다.

-- APPROVAL_CASE · 최종 결정 대상 (담당 C)
CREATE TABLE IF NOT EXISTS approval_case (
    case_id          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    review_id        BIGINT NOT NULL UNIQUE,
    version_id       BIGINT NOT NULL UNIQUE,
    state            VARCHAR(30) NOT NULL,
    rejection_reason VARCHAR(2000),
    decided_at       TIMESTAMP,
    decision_key     VARCHAR(64) UNIQUE,
    CONSTRAINT pk_approval_case PRIMARY KEY (case_id),
    CONSTRAINT fk_approval_case_review_id FOREIGN KEY (review_id) REFERENCES review (review_id),
    CONSTRAINT fk_approval_case_version_id FOREIGN KEY (version_id) REFERENCES work_version (version_id),
    CONSTRAINT ck_approval_case_state CHECK (state IN ('PENDING', 'REJECTED', 'APPROVED'))
);

-- APPROVAL · 승인 기록 (담당 C)
CREATE TABLE IF NOT EXISTS approval (
    approval_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    case_id     BIGINT NOT NULL UNIQUE,
    approver_id BIGINT NOT NULL,
    approved_at TIMESTAMP NOT NULL,
    CONSTRAINT pk_approval PRIMARY KEY (approval_id),
    CONSTRAINT fk_approval_case_id FOREIGN KEY (case_id) REFERENCES approval_case (case_id),
    CONSTRAINT fk_approval_approver_id FOREIGN KEY (approver_id) REFERENCES "user" (user_id)
);

-- REVOCATION · 철회 기록 (담당 C)
CREATE TABLE IF NOT EXISTS revocation (
    revocation_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    approval_id   BIGINT NOT NULL UNIQUE,
    actor_id      BIGINT NOT NULL,
    reason        VARCHAR(2000) NOT NULL,
    revoked_at    TIMESTAMP NOT NULL,
    request_key   VARCHAR(64) NOT NULL UNIQUE,
    CONSTRAINT pk_revocation PRIMARY KEY (revocation_id),
    CONSTRAINT fk_revocation_approval_id FOREIGN KEY (approval_id) REFERENCES approval (approval_id),
    CONSTRAINT fk_revocation_actor_id FOREIGN KEY (actor_id) REFERENCES "user" (user_id)
);

-- CERTIFICATE · 증명서 (담당 C)
-- immutable_payload는 키를 정렬한 JSON 문자열 그대로 둔다(서명 대상). jsonb로 바꾸지 않는다.
CREATE TABLE IF NOT EXISTS certificate (
    certificate_id    BIGINT GENERATED BY DEFAULT AS IDENTITY,
    approval_id       BIGINT NOT NULL UNIQUE,
    immutable_payload JSON NOT NULL,
    signing_state     VARCHAR(30) NOT NULL,
    signature         TEXT,
    key_id            VARCHAR(50),
    issued_at         TIMESTAMP,
    CONSTRAINT pk_certificate PRIMARY KEY (certificate_id),
    CONSTRAINT fk_certificate_approval_id FOREIGN KEY (approval_id) REFERENCES approval (approval_id),
    CONSTRAINT ck_certificate_signing_state CHECK (signing_state IN ('PENDING', 'READY', 'FAILED'))
);

-- OUTBOX_EVENT · 서명 요청 (담당 C)
CREATE TABLE IF NOT EXISTS outbox_event (
    event_id       BIGINT GENERATED BY DEFAULT AS IDENTITY,
    certificate_id BIGINT NOT NULL UNIQUE,
    delivery_state VARCHAR(30) NOT NULL,
    retry_count    INT DEFAULT 0 NOT NULL,
    CONSTRAINT pk_outbox_event PRIMARY KEY (event_id),
    CONSTRAINT fk_outbox_event_certificate_id FOREIGN KEY (certificate_id) REFERENCES certificate (certificate_id),
    CONSTRAINT ck_outbox_event_delivery_state CHECK (delivery_state IN ('PENDING', 'DELIVERED', 'FAILED'))
);

-- SHARE_LINK · 공유 링크 (담당 C)
-- 토큰 원문은 저장하지 않고 SHA-256만 둔다.
CREATE TABLE IF NOT EXISTS share_link (
    link_id        BIGINT GENERATED BY DEFAULT AS IDENTITY,
    certificate_id BIGINT NOT NULL,
    token_hash     CHAR(64) NOT NULL UNIQUE,
    expires_at     TIMESTAMP,
    disabled_at    TIMESTAMP,
    CONSTRAINT pk_share_link PRIMARY KEY (link_id),
    CONSTRAINT fk_share_link_certificate_id FOREIGN KEY (certificate_id) REFERENCES certificate (certificate_id)
);
