-- 기준: 팀원공유용_v3/11_DB/HAVE_데이터베이스_설계_검토반영.md의 최종 스키마(형식은 6단계, 코드 값은 부록 A).
-- 설계서의 스키마 정의(팀원공유용_v3/_소스/schema_1123.py)를 그대로 옮겼다. 이제부터는 이 파일이 원본이고 테이블 담당자가 고친다.
-- 설계서와 다르게 둔 곳(기본값 · NULL 허용 · 자동 번호)은 docs/design-changes.md에 적었다.
-- 여러 번 실행해도 되도록 IF NOT EXISTS를 쓴다. 열을 바꾸면 이 파일을 고치고, 이미 만든 로컬 DB는 지우고 다시 만든다.

-- REVISION · 수정 회차 (담당 A)
-- 검토자의 수정 요청(review_id) 또는 최종 승인자의 반려(case_id) 중 정확히 하나로 만들어진다.
CREATE TABLE IF NOT EXISTS revision (
    revision_id          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    review_id            BIGINT UNIQUE,
    case_id              BIGINT UNIQUE,
    submitted_version_id BIGINT UNIQUE,
    state                VARCHAR(30) NOT NULL,
    due_date             DATE,
    change_note          VARCHAR(2000) DEFAULT '' NOT NULL,
    response             VARCHAR(2000) DEFAULT '' NOT NULL,
    CONSTRAINT pk_revision PRIMARY KEY (revision_id),
    CONSTRAINT fk_revision_review_id FOREIGN KEY (review_id) REFERENCES review (review_id),
    CONSTRAINT fk_revision_case_id FOREIGN KEY (case_id) REFERENCES approval_case (case_id),
    CONSTRAINT fk_revision_submitted_version_id FOREIGN KEY (submitted_version_id) REFERENCES work_version (version_id),
    CONSTRAINT ck_revision_state CHECK (state IN ('OPEN', 'IN_PROGRESS', 'SUBMITTED', 'EXPIRED')),
    CONSTRAINT ck_revision_basis CHECK ((review_id IS NULL) <> (case_id IS NULL)),
    CONSTRAINT ck_revision_submitted CHECK (state <> 'SUBMITTED' OR submitted_version_id IS NOT NULL)
);

-- REVISION_DRAFT_FILE · 수정 초안 파일 (담당 A)
CREATE TABLE IF NOT EXISTS revision_draft_file (
    revision_id BIGINT,
    file_seq    INT,
    file_uri    VARCHAR(2000) NOT NULL,
    CONSTRAINT pk_revision_draft_file PRIMARY KEY (revision_id, file_seq),
    CONSTRAINT fk_revision_draft_file_revision_id FOREIGN KEY (revision_id) REFERENCES revision (revision_id)
);

-- FEEDBACK_RESPONSE · 보완 항목 답변 (담당 A)
CREATE TABLE IF NOT EXISTS feedback_response (
    feedback_item_id BIGINT,
    applied          BOOLEAN NOT NULL,
    response         VARCHAR(1000) NOT NULL,
    responded_at     TIMESTAMP NOT NULL,
    CONSTRAINT pk_feedback_response PRIMARY KEY (feedback_item_id),
    CONSTRAINT fk_feedback_response_feedback_item_id FOREIGN KEY (feedback_item_id) REFERENCES feedback_item (feedback_item_id)
);
