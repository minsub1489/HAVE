-- 설계서의 스키마 정의(팀원공유용_v3/_소스/schema_1123.py)를 그대로 옮겼다. 이제부터는 이 파일이 원본이고 테이블 담당자가 고친다.
-- 설계서와 다르게 둔 곳(기본값 · NULL 허용 · 자동 번호)은 docs/design-changes.md에 적었다.
-- 여러 번 실행해도 되도록 IF NOT EXISTS를 쓴다. 열을 바꾸면 이 파일을 고치고, 이미 만든 로컬 DB는 지우고 다시 만든다.

-- WORK_VERSION · 결과물 버전 (담당 A)
-- status는 setWorkStatus만 바꾼다. revision은 낙관적 잠금 번호다.
CREATE TABLE IF NOT EXISTS work_version (
    version_id    BIGINT GENERATED BY DEFAULT AS IDENTITY,
    work_id       BIGINT NOT NULL,
    version_no    INT NOT NULL,
    file_hash     CHAR(64) NOT NULL,
    file_uri      VARCHAR(2000) NOT NULL,
    status        VARCHAR(30) NOT NULL,
    change_reason VARCHAR(2000),
    created_at    TIMESTAMP NOT NULL,
    revision      INT DEFAULT 0 NOT NULL,
    CONSTRAINT pk_work_version PRIMARY KEY (version_id),
    CONSTRAINT uq_work_version_no UNIQUE (work_id, version_no),
    CONSTRAINT fk_work_version_work_id FOREIGN KEY (work_id) REFERENCES work (work_id),
    CONSTRAINT ck_work_version_version_no CHECK (version_no >= 1),
    CONSTRAINT ck_work_version_status CHECK (status IN ('DRAFT', 'SUBMITTED', 'CHALLENGE_PENDING', 'REVIEW_PENDING', 'IN_REVIEW', 'REVISION_REQUIRED', 'APPROVAL_PENDING', 'APPROVED'))
);

-- AI_DISCLOSURE · AI 신고 사본 (담당 A)
CREATE TABLE IF NOT EXISTS ai_disclosure (
    version_id  BIGINT,
    usage_scope VARCHAR(5000) NOT NULL,
    no_ai_used  BOOLEAN NOT NULL,
    CONSTRAINT pk_ai_disclosure PRIMARY KEY (version_id),
    CONSTRAINT fk_ai_disclosure_version_id FOREIGN KEY (version_id) REFERENCES work_version (version_id)
);

-- AI_TOOL_USAGE · AI 도구 사용 (담당 A)
CREATE TABLE IF NOT EXISTS ai_tool_usage (
    version_id   BIGINT,
    tool_seq     INT,
    tool_name    VARCHAR(100) NOT NULL,
    model_name   VARCHAR(100) NOT NULL,
    usage_method VARCHAR(100) NOT NULL,
    contribution VARCHAR(2000) NOT NULL,
    CONSTRAINT pk_ai_tool_usage PRIMARY KEY (version_id, tool_seq),
    CONSTRAINT fk_ai_tool_usage_version_id FOREIGN KEY (version_id) REFERENCES ai_disclosure (version_id)
);

-- CONTRIBUTION · 기여 기록 (담당 A)
CREATE TABLE IF NOT EXISTS contribution (
    version_id BIGINT,
    record_id  INT,
    stage      VARCHAR(30) NOT NULL,
    actor_type VARCHAR(30) NOT NULL,
    note       VARCHAR(2000) NOT NULL,
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT pk_contribution PRIMARY KEY (version_id, record_id),
    CONSTRAINT fk_contribution_version_id FOREIGN KEY (version_id) REFERENCES work_version (version_id),
    CONSTRAINT ck_contribution_stage CHECK (stage IN ('IDEA', 'DRAFT', 'REVISION', 'SOURCE_VERIFICATION')),
    CONSTRAINT ck_contribution_actor_type CHECK (actor_type IN ('AI', 'HUMAN', 'MIXED'))
);

-- EVIDENCE_ITEM · 근거자료 (담당 A)
CREATE TABLE IF NOT EXISTS evidence_item (
    evidence_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    type        VARCHAR(30) NOT NULL,
    title       VARCHAR(200) NOT NULL,
    uri         VARCHAR(2000) NOT NULL,
    file_hash   CHAR(64),
    CONSTRAINT pk_evidence_item PRIMARY KEY (evidence_id),
    CONSTRAINT ck_evidence_item_type CHECK (type IN ('WEB_SOURCE', 'REFERENCE', 'PROMPT_LOG', 'SUPPORT_FILE'))
);

-- VERSION_EVIDENCE · 버전-근거 연결 (담당 A)
CREATE TABLE IF NOT EXISTS version_evidence (
    version_id  BIGINT,
    evidence_id BIGINT,
    CONSTRAINT pk_version_evidence PRIMARY KEY (version_id, evidence_id),
    CONSTRAINT fk_version_evidence_version_id FOREIGN KEY (version_id) REFERENCES work_version (version_id),
    CONSTRAINT fk_version_evidence_evidence_id FOREIGN KEY (evidence_id) REFERENCES evidence_item (evidence_id)
);
