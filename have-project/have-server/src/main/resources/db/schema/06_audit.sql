-- 여러 번 실행해도 되도록 IF NOT EXISTS를 쓴다. 열을 바꾸면 이 파일을 고치고, 이미 만든 로컬 DB는 지우고 다시 만든다.

-- AUDIT_EVENT · 감사 이벤트 (담당 D)
-- 추가만 한다(append-only). 운영 계정에는 UPDATE·DELETE 권한을 주지 않는다. prev_hash는 같은 작업의 직전 event_hash.
CREATE TABLE IF NOT EXISTS audit_event (
    event_id    BIGINT GENERATED BY DEFAULT AS IDENTITY,
    work_id     BIGINT NOT NULL,
    version_no  INT,
    actor_id    BIGINT,
    action      VARCHAR(40) NOT NULL,
    reason      VARCHAR(2000),
    occurred_at TIMESTAMP NOT NULL,
    prev_hash   CHAR(64) NOT NULL,
    event_hash  CHAR(64) NOT NULL,
    CONSTRAINT pk_audit_event PRIMARY KEY (event_id),
    CONSTRAINT fk_audit_event_work_id FOREIGN KEY (work_id) REFERENCES work (work_id),
    CONSTRAINT fk_audit_event_work_version FOREIGN KEY (work_id, version_no) REFERENCES work_version (work_id, version_no),
    CONSTRAINT fk_audit_event_actor_id FOREIGN KEY (actor_id) REFERENCES "user" (user_id),
    CONSTRAINT ck_audit_event_action CHECK (action IN ('CREATE_WORK', 'ADD_CONTRIBUTION', 'UPLOAD_VERSION', 'ASSESS_RISK', 'REQUEST_REVIEW', 'CANCEL_REQUEST', 'SUBMIT_ANSWERS', 'START_REVIEW', 'HALT_REVIEW', 'PASS_REVIEW', 'REQUEST_REVISION', 'RESUBMIT', 'APPROVE', 'REJECT', 'ISSUE_CERTIFICATE', 'ISSUE_FAILED', 'RETRY_ISSUE', 'SHARE_LINK_CREATED', 'SHARE_LINK_DISABLED', 'REVOKE', 'VERIFY'))
);
CREATE INDEX IF NOT EXISTS ix_audit_event_work ON audit_event (work_id, event_id);

-- NOTIFICATION · 알림 (담당 D)
CREATE TABLE IF NOT EXISTS notification (
    notification_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id         BIGINT NOT NULL,
    version_id      BIGINT NOT NULL,
    type            VARCHAR(30) NOT NULL,
    created_at      TIMESTAMP NOT NULL,
    read_at         TIMESTAMP,
    CONSTRAINT pk_notification PRIMARY KEY (notification_id),
    CONSTRAINT fk_notification_user_id FOREIGN KEY (user_id) REFERENCES "user" (user_id),
    CONSTRAINT fk_notification_version_id FOREIGN KEY (version_id) REFERENCES work_version (version_id),
    CONSTRAINT ck_notification_type CHECK (type IN ('REVIEW_REQUESTED', 'REQUEST_CANCELED', 'ANSWERS_SUBMITTED', 'REVISION_REQUESTED', 'RESUBMITTED', 'REVIEW_PASSED', 'APPROVED', 'REJECTED', 'CERTIFICATE_ISSUED', 'APPROVAL_REVOKED'))
);
CREATE INDEX IF NOT EXISTS ix_notification_user ON notification (user_id, created_at);
