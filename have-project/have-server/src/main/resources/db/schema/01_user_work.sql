-- HAVE 스키마 01 — 사용자·작업
-- 기준: 팀원공유용_v3/11_DB/HAVE_데이터베이스_설계_검토반영.md의 최종 스키마(형식은 6단계, 코드 값은 부록 A).
-- 설계서의 스키마 정의(팀원공유용_v3/_소스/schema_1123.py)를 그대로 옮겼다. 이제부터는 이 파일이 원본이고 테이블 담당자가 고친다.
-- 설계서와 다르게 둔 곳(기본값 · NULL 허용 · 자동 번호)은 docs/design-changes.md에 적었다.
-- 여러 번 실행해도 되도록 IF NOT EXISTS를 쓴다. 열을 바꾸면 이 파일을 고치고, 이미 만든 로컬 DB는 지우고 다시 만든다.

-- USER · 사용자 (담당 B)
-- user는 PostgreSQL 예약어라 항상 큰따옴표로 감싼다: SELECT … FROM "user". 따옴표 없이 쓰면 현재 접속 계정 이름이 나온다.
CREATE TABLE IF NOT EXISTS "user" (
    user_id       BIGINT GENERATED BY DEFAULT AS IDENTITY,
    name          VARCHAR(50) NOT NULL,
    email         VARCHAR(254) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    CONSTRAINT pk_user PRIMARY KEY (user_id)
);

-- WORK · 작업 (담당 A)
-- 버전이 생기기 전의 AI 신고 초안은 ai_disclosure_draft에 둔다.
CREATE TABLE IF NOT EXISTS work (
    work_id             BIGINT GENERATED BY DEFAULT AS IDENTITY,
    owner_id            BIGINT NOT NULL,
    title               VARCHAR(100) NOT NULL,
    ai_disclosure_draft JSON,
    CONSTRAINT pk_work PRIMARY KEY (work_id),
    CONSTRAINT fk_work_owner_id FOREIGN KEY (owner_id) REFERENCES "user" (user_id)
);

-- WORK_MEMBER · 작업 멤버 (담당 B)
CREATE TABLE IF NOT EXISTS work_member (
    work_id BIGINT,
    user_id BIGINT,
    role    VARCHAR(30),
    CONSTRAINT pk_work_member PRIMARY KEY (work_id, user_id, role),
    CONSTRAINT fk_work_member_work_id FOREIGN KEY (work_id) REFERENCES work (work_id),
    CONSTRAINT fk_work_member_user_id FOREIGN KEY (user_id) REFERENCES "user" (user_id),
    CONSTRAINT ck_work_member_role CHECK (role IN ('AUTHOR', 'REVIEWER', 'APPROVER'))
);
-- 검토자와 최종 승인자는 작업마다 한 명이다(가이드라인 5.4, docs/design-changes.md 1.1의 14번). 작성자는 제한하지 않는다.
CREATE UNIQUE INDEX IF NOT EXISTS uq_work_member_designated ON work_member (work_id, role) WHERE role IN ('REVIEWER', 'APPROVER');
